-- ============================================================
-- PRODUCTS POLICIES
-- ============================================================

drop policy if exists "Anyone can read active products"
on public.products;

create policy "Anyone can read active products"
on public.products
for select
to anon, authenticated
using (is_active = true);


-- Customer clients cannot insert/update/delete products.
-- Admin operations use the server-side service role.


-- ============================================================
-- ORDERS POLICIES
-- ============================================================

drop policy if exists "Users can create their own orders"
on public.orders;

create policy "Users can create their own orders"
on public.orders
for insert
to authenticated
with check (
    auth.uid() = user_id
);


drop policy if exists "Users can view their own orders"
on public.orders;

create policy "Users can view their own orders"
on public.orders
for select
to authenticated
using (
    auth.uid() = user_id
);


-- No customer update/delete policy.
-- This prevents customers from changing order status
-- or changing another customer's information.


-- ============================================================
-- ORDER ITEMS POLICIES
-- ============================================================

drop policy if exists "Users can create items for their own orders"
on public.order_items;

create policy "Users can create items for their own orders"
on public.order_items
for insert
to authenticated
with check (
    exists (
        select 1
        from public.orders
        where orders.id = order_items.order_id
        and orders.user_id = auth.uid()
    )
);


drop policy if exists "Users can view items from their own orders"
on public.order_items;

create policy "Users can view items from their own orders"
on public.order_items
for select
to authenticated
using (
    exists (
        select 1
        from public.orders
        where orders.id = order_items.order_id
        and orders.user_id = auth.uid()
    )
);


-- ============================================================
-- STORE CONFIG POLICIES
-- ============================================================

drop policy if exists "Authenticated users can read store config"
on public.store_config;

create policy "Authenticated users can read store config"
on public.store_config
for select
to authenticated
using (true);


