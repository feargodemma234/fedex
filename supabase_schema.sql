-- ============================================================
-- UPDATED_AT TRIGGER
-- ============================================================

create or replace function public.update_updated_at_column()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;


drop trigger if exists products_updated_at
on public.products;

create trigger products_updated_at
before update on public.products
for each row
execute function public.update_updated_at_column();


drop trigger if exists orders_updated_at
on public.orders;

create trigger orders_updated_at
before update on public.orders
for each row
execute function public.update_updated_at_column();


drop trigger if exists store_config_updated_at
on public.store_config;

create trigger store_config_updated_at
before update on public.store_config
for each row
execute function public.update_updated_at_column();


